-- TokenDanceChat PostgreSQL schema (P0).
--
-- Mirrors the active SQLite schema documented in docs/pg-migration.md.
-- Deliberate differences from SQLite:
--   * implicit rowid -> explicit identity column `seq` (ordering / frozen run input);
--   * Unix-millisecond integers -> timestamptz (0 sentinels become NULL);
--   * 0/1 integers -> boolean;
--   * JSON stored as TEXT -> jsonb (empty parts become NULL);
--   * budget_day TEXT -> date;
--   * pg_trgm replaces FTS5 for message search.
--
-- The agent_tasks domain (6 tables) is P1 and intentionally absent here.
-- River keeps its own schema and migration table; do not add job-queue tables here.

-- +goose Up
-- pg_trgm is a trusted extension since PostgreSQL 13: the database owner can
-- create it without superuser. Managed providers ship it.
CREATE EXTENSION IF NOT EXISTS pg_trgm;

CREATE TABLE rooms (
    id   text PRIMARY KEY,
    name text NOT NULL UNIQUE
);

CREATE TABLE messages (
    id           text PRIMARY KEY,
    -- Replaces SQLite rowid. BY DEFAULT (not ALWAYS) so the one-shot import can
    -- copy the source rowid and preserve tie-breaking order; application code
    -- never writes this column.
    seq          bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    username     text NOT NULL,
    content      text NOT NULL,
    created_at   timestamptz NOT NULL DEFAULT now(),
    reply_to_id  text NOT NULL DEFAULT '',
    room_id      text NOT NULL DEFAULT '',
    deleted      boolean NOT NULL DEFAULT false,
    edited       boolean NOT NULL DEFAULT false,
    to_user      text NOT NULL DEFAULT '',
    thread_id    text NOT NULL DEFAULT '',
    -- assistant-ui parts. NULL means "no parts"; the SQLite side stored ''.
    parts        jsonb,
    -- Bot run linkage. messages_run_final keeps "one final message per run";
    -- later burst segments use '<run>#<n>' and stay groupable.
    run_id       text NOT NULL DEFAULT '',
    -- Canonical principal (oidc:<sub>, local:<user>, guest:<id>). Never trust a
    -- handle supplied by the client.
    actor_id     text NOT NULL DEFAULT ''
);

CREATE INDEX idx_messages_timestamp ON messages (created_at DESC, seq DESC);
CREATE INDEX idx_messages_room ON messages (room_id, created_at DESC, seq DESC);
CREATE INDEX idx_messages_to_user ON messages (to_user, created_at DESC, seq DESC);
CREATE INDEX idx_messages_thread ON messages (thread_id, created_at);
CREATE INDEX idx_messages_actor ON messages (actor_id);
CREATE UNIQUE INDEX messages_run_final ON messages (run_id) WHERE run_id <> '';

-- Search: pg_trgm GIN index supports ILIKE '%term%' and similarity() ranking.
-- See docs/pg-migration.md for the FTS5 trade-off and the planned CJK upgrade.
CREATE INDEX idx_messages_trgm ON messages USING gin (content gin_trgm_ops);

CREATE TABLE reactions (
    -- SQLite exposed reactions in rowid order; keep that user-visible ordering.
    seq        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id text NOT NULL REFERENCES messages (id) ON DELETE CASCADE,
    emoji      text NOT NULL,
    username   text NOT NULL,
    UNIQUE (message_id, emoji, username)
);
CREATE INDEX idx_reactions_message ON reactions (message_id);

CREATE TABLE blocked_users (
    username text NOT NULL,
    blocked  text NOT NULL,
    PRIMARY KEY (username, blocked)
);

CREATE TABLE pinned_messages (
    room_id    text NOT NULL DEFAULT '',
    message_id text NOT NULL,
    pinned_by  text NOT NULL,
    pinned_at  timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (room_id, message_id)
);

CREATE TABLE notification_prefs (
    username     text NOT NULL,
    key          text NOT NULL,
    -- NULL = not muted (SQLite stored 0).
    muted_until  timestamptz,
    show_preview boolean NOT NULL DEFAULT true,
    PRIMARY KEY (username, key)
);

CREATE TABLE user_profiles (
    username     text PRIMARY KEY,
    display_name text NOT NULL DEFAULT '',
    avatar_url   text NOT NULL DEFAULT '',
    bio          text NOT NULL DEFAULT '',
    status       text NOT NULL DEFAULT '',
    -- NULL = never seen (SQLite stored 0).
    last_seen    timestamptz
);

CREATE TABLE polls (
    id              text PRIMARY KEY,
    room_id         text NOT NULL DEFAULT 'public',
    creator         text NOT NULL,
    question        text NOT NULL,
    options         jsonb NOT NULL,
    multiple_choice boolean NOT NULL DEFAULT false,
    is_anonymous    boolean NOT NULL DEFAULT false,
    is_closed       boolean NOT NULL DEFAULT false,
    votes           jsonb NOT NULL DEFAULT '{}'::jsonb,
    voters          jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at      timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE custom_emojis (
    id         text PRIMARY KEY,
    name       text NOT NULL UNIQUE,
    url        text NOT NULL,
    uploader   text NOT NULL,
    room_id    text NOT NULL DEFAULT '',
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_custom_emojis_name ON custom_emojis (name);

-- Local password auth is retained because the local/guest mode still uses it.
-- Production identity remains Account OIDC (oidc_users).
CREATE TABLE users (
    username      text PRIMARY KEY,
    password_hash text NOT NULL,
    invited_by    text NOT NULL DEFAULT '',
    created_at    timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE invite_codes (
    code       text PRIMARY KEY,
    creator    text NOT NULL,
    max_uses   integer NOT NULL DEFAULT 5,
    use_count  integer NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE oidc_users (
    sub                text PRIMARY KEY,
    chat_username      text NOT NULL UNIQUE,
    email              text NOT NULL DEFAULT '',
    preferred_username text NOT NULL DEFAULT '',
    name               text NOT NULL DEFAULT '',
    picture            text NOT NULL DEFAULT '',
    created_at         timestamptz NOT NULL DEFAULT now(),
    updated_at         timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_oidc_users_chat_username ON oidc_users (chat_username);

-- Subject-scoped logout generation. Persisted so a stale Chat cookie cannot
-- become valid again after a restart.
CREATE TABLE oidc_logout_epochs (
    sub        text PRIMARY KEY,
    generation bigint NOT NULL DEFAULT 0,
    updated_at timestamptz NOT NULL DEFAULT now()
);

-- JTI ledger makes Account's back-channel retries idempotent.
CREATE TABLE oidc_backchannel_logout_jtis (
    jti           text PRIMARY KEY,
    claims_sha256 text NOT NULL,
    received_at   timestamptz NOT NULL DEFAULT now(),
    expires_at    timestamptz NOT NULL
);
CREATE INDEX idx_oidc_logout_jtis_expires ON oidc_backchannel_logout_jtis (expires_at);

CREATE TABLE bot_runs (
    id                   text PRIMARY KEY,
    message_id           text NOT NULL UNIQUE,
    trigger_message_id   text NOT NULL UNIQUE,
    actor_id             text NOT NULL,
    requested_by         text NOT NULL,
    room_id              text NOT NULL,
    to_user              text NOT NULL,
    bot_name             text NOT NULL,
    -- Private lane ('' = main chat). Public runs always carry ''.
    thread_id            text NOT NULL DEFAULT '',
    session_generation   bigint NOT NULL DEFAULT 0,
    -- NULL = no expiry (SQLite stored 0).
    session_expires_at   timestamptz,
    status               text NOT NULL CHECK (status IN ('queued', 'running', 'completed', 'failed', 'cancelled')),
    reason               text NOT NULL DEFAULT '',
    -- Frozen trigger input snapshot; never rewritten after enqueue.
    input_json           jsonb NOT NULL,
    -- HKT calendar day fixed at enqueue time.
    budget_day           date NOT NULL,
    ip_key               text NOT NULL DEFAULT '',
    reserved_tokens      bigint NOT NULL DEFAULT 0,
    charged_tokens       bigint NOT NULL DEFAULT 0,
    created_at           timestamptz NOT NULL DEFAULT now(),
    updated_at           timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX bot_runs_budget_day ON bot_runs (budget_day);
CREATE INDEX bot_runs_actor ON bot_runs (actor_id, status);
CREATE INDEX bot_runs_queue ON bot_runs (room_id, to_user, status, created_at);

CREATE TABLE bot_web_calls (
    id                 text PRIMARY KEY,
    run_id             text NOT NULL REFERENCES bot_runs (id),
    tool_call_id       text NOT NULL,
    tool               text NOT NULL,
    provider           text NOT NULL,
    attempt            integer NOT NULL,
    price_version      text NOT NULL,
    budget_day         date NOT NULL,
    reserved_micro_cny bigint NOT NULL,
    charged_micro_cny  bigint NOT NULL,
    status             text NOT NULL,
    created_at         timestamptz NOT NULL DEFAULT now(),
    updated_at         timestamptz NOT NULL DEFAULT now(),
    UNIQUE (run_id, tool_call_id)
);
CREATE INDEX bot_web_calls_day ON bot_web_calls (budget_day);

CREATE TABLE bot_web_sources (
    id           text PRIMARY KEY,
    -- Discovery order drives citation numbering; SQLite used rowid.
    seq          bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    run_id       text NOT NULL REFERENCES bot_runs (id),
    url          text NOT NULL,
    title        text NOT NULL,
    status       text NOT NULL,
    content      text NOT NULL,
    content_hash text NOT NULL,
    retrieved_at timestamptz NOT NULL,
    truncated    boolean NOT NULL DEFAULT false,
    error_code   text NOT NULL DEFAULT '',
    extractor    text NOT NULL DEFAULT 'deepseek-fetch-v1',
    UNIQUE (run_id, url)
);

-- +goose Down
-- Drop in reverse dependency order. pg_trgm is left installed: it may be shared
-- with other schemas in the same database.
DROP TABLE IF EXISTS bot_web_sources;
DROP TABLE IF EXISTS bot_web_calls;
DROP TABLE IF EXISTS bot_runs;
DROP TABLE IF EXISTS oidc_backchannel_logout_jtis;
DROP TABLE IF EXISTS oidc_logout_epochs;
DROP TABLE IF EXISTS oidc_users;
DROP TABLE IF EXISTS invite_codes;
DROP TABLE IF EXISTS users;
DROP TABLE IF EXISTS custom_emojis;
DROP TABLE IF EXISTS polls;
DROP TABLE IF EXISTS user_profiles;
DROP TABLE IF EXISTS notification_prefs;
DROP TABLE IF EXISTS pinned_messages;
DROP TABLE IF EXISTS blocked_users;
DROP TABLE IF EXISTS reactions;
DROP TABLE IF EXISTS messages;
DROP TABLE IF EXISTS rooms;
